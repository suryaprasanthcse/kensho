import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { main } from '@kensho/cli';
import type { AssetGateReport } from '@kensho/gates-asset';
import { Ledger } from '@kensho/hyper3d_rodin';
import { OUT_DIR } from './paths.ts';

/** Offline: turns bench/out/live/{jobs,wire}.json and the ledger into LIVE_VERIFICATION.md. No network, no key. */
const LIVE = join(OUT_DIR, 'live');
interface Job {
  id: string;
  purpose: string;
  status: string;
  error?: string;
  consumed?: number;
  expected_credits?: number;
  polls?: { at_ms: number; status: string }[];
  total_ms?: number;
  download_ms?: number;
  submit_ms?: number;
  bytes?: number;
  glb?: string;
  uuid?: string;
}
interface Wire {
  method: string;
  url: string;
  status: number;
  ms: number;
  headers: Record<string, string>;
  request_fields?: string[];
  response_body?: string;
}

const jobs = JSON.parse(readFileSync(join(LIVE, 'jobs.json'), 'utf8')) as Job[];
const wire = JSON.parse(readFileSync(join(LIVE, 'wire.json'), 'utf8')) as Wire[];
const ledger = new Ledger(join(LIVE, 'ledger.jsonl')).entries();

async function gate(file: string, tier: string, box?: string): Promise<AssetGateReport> {
  let out = '';
  await main(['asset-gate', file, '--tier', tier, '--class', 'prop', '--body', 'dynamic', ...(box ? ['--box-um', box] : []), '--timeout-ms', '300000'], { stdout: (t) => void (out += t), stderr: () => {} });
  return JSON.parse(out) as AssetGateReport;
}
const codes = (r: AssetGateReport) => [...new Set(r.diagnostics.filter((d) => d.severity === 'error').map((d) => d.code))].join(', ') || '-';
const secs = (ms: number | undefined) => (ms === undefined ? '-' : (ms / 1000).toFixed(1));

const md: string[] = [];
const w = (t = '') => md.push(t);
w('# Live Hyper3D Rodin REST verification');
w('Generated by `pnpm live-report` from the ledger, the sanitized wire record and the downloaded files. Authorization headers and signed URL queries were never recorded.');
w();

// ---- spend ----
const accepted = ledger.filter((e) => e.event === 'accepted');
const spent = accepted.reduce((n, e) => n + (e.consumed_mc ?? 0), 0) / 1000;
w('## Spend');
w();
w(`${accepted.length} jobs accepted, **${spent} credits** consumed per the ledger (ceiling 5). Halts or drift events: ${ledger.filter((e) => e.event === 'halted' || e.event === 'drift').length}. Rejections: ${ledger.filter((e) => e.event === 'rejected').length}. Unknown submits: ${ledger.filter((e) => e.event === 'submit_unknown').length}.`);
w();
w('| Job | Tier | Documented price | `consumed` reported | Sub-jobs |');
w('|---|---|---:|---:|---:|');
for (const e of accepted) {
  const j = jobs.find((x) => x.uuid === e.uuid);
  w(`| ${j?.id ?? e.uuid} | ${e.tier} | ${(e.expected_mc ?? 0) / 1000} | ${(e.consumed_mc ?? 0) / 1000} | ${e.job_uuids?.length ?? '?'} |`);
}
w();

// ---- wire ----
w('## What the wire showed');
w();
const byPath = (p: string) => wire.filter((x) => x.url.includes(p));
const lim = (p: string) => {
  const h = byPath(p)[0]?.headers ?? {};
  return `${h['x-ratelimit-limit'] ?? '?'} per ${h['x-ratelimit-reset'] ?? '?'} s window`;
};
w('| Call | HTTP | Observed rate limit | Request fields / response |');
w('|---|---:|---|---|');
w(`| POST /api/v2/rodin | ${[...new Set(byPath('/api/v2/rodin').map((x) => x.status))].join(',')} | ${lim('/api/v2/rodin')} | fields: ${[...new Set(byPath('/api/v2/rodin').flatMap((x) => x.request_fields ?? []))].join(', ')}; response: message, prompt, submit_time, uuid, jobs.uuids (3), jobs.subscription_key, consumed |`);
w(`| POST /api/v2/status | ${[...new Set(byPath('/api/v2/status').map((x) => x.status))].join(',')} | ${lim('/api/v2/status')} | response: jobs[] of {uuid, status}; three jobs per submission |`);
w(`| POST /api/v2/download | ${[...new Set(byPath('/api/v2/download').map((x) => x.status))].join(',')} | ${lim('/api/v2/download')} | response: list[] of {name, url}; an unfinished task returns an empty list, not an error |`);
const files = wire.filter((x) => x.url.startsWith('https://file.'));
w(`| GET file host | ${[...new Set(files.map((x) => x.status))].join(',')} | none seen | ${files.length} downloads, median ${Math.round([...files.map((x) => x.ms)].sort((a, b) => a - b)[Math.floor(files.length / 2)] ?? 0)} ms; the key is not sent to this host |`);
const early = byPath('/api/v2/download').filter((x) => (x.response_body ?? '').includes('"list":[]')).length;
w();
w(`- Status values seen: ${[...new Set(wire.flatMap((x) => [...(x.response_body ?? '').matchAll(/"status":"(\w+)"/g)].map((m) => m[1]!)))].join(', ')}.`);
w(`- A download requested while a sub-job was unfinished returned an empty list ${early} time(s), as documented. The first live run exposed this: the client had treated the first \`Done\` as completion. It now requires every sub-job to be \`Done\`.`);
w('- The submit response has **no tier field**, so a silent downgrade cannot be seen from the echo; the cost check and the downloaded asset are the defences.');
w('- `seed`, `quality_override`, `mesh_mode`, `geometry_file_format`, repeated `bbox_condition` fields and a repeated `addons` field were all accepted with HTTP 201.');
w();

// ---- polling ----
w('## Polling and timing');
w();
w('Seven jobs were in flight at once, then two more one after another. Polls began at 5 s and backed off by 1.5× to a 30 s ceiling, per the documented guidance.');
w();
w('| Job | Time to done (s) | Polls | Poll offsets (s) | Download (ms) | Bytes |');
w('|---|---:|---:|---|---:|---:|');
for (const j of jobs) w(`| ${j.id} | ${secs(j.total_ms)} | ${j.polls?.length ?? 0} | ${(j.polls ?? []).map((p) => secs(p.at_ms)).join(', ')} | ${j.download_ms ?? '-'} | ${j.bytes ?? '-'} |`);
const t = jobs.filter((j) => j.status === 'ok').map((j) => j.total_ms!).sort((a, b) => a - b);
w();
w(`Time to done: min ${secs(t[0])} s, median ${secs(t[Math.floor(t.length / 2)])} s, max ${secs(t[t.length - 1])} s (n=${t.length}).`);
w();

// ---- gate on the downloads ----
w('## The downloads through `asset-gate` (class prop, dynamic)');
w();
w('| Job | Prompt purpose | Tris | Degenerate tris | Textures | Mobile | Desktop | Mobile errors | Floating shells |');
w('|---|---|---:|---:|---|---|---|---|---:|');
const BOX: Record<string, [number, number, number]> = { j03_crate_bbox_200_100_50: [200, 100, 50], j04_crate_bbox_50_100_200: [50, 100, 200], j05_crate_bbox_100_200_50: [100, 200, 50] };
const bboxRows: string[] = [];
const dims: Record<string, number[]> = {};
for (const j of jobs.filter((x) => x.glb)) {
  const file = join(LIVE, j.glb!);
  const m = await gate(file, 'mobile');
  const d = await gate(file, 'desktop');
  const ms = m.measures as Record<string, number | number[]>;
  dims[j.id] = ms.bbox_um as number[];
  w(`| ${j.id} | ${j.purpose} | ${ms.triangles} | ${ms.degenerate_triangles} | ${ms.images}×${ms.texture_max_dim} px, ${((ms.texture_gpu_bytes as number) / 1048576).toFixed(0)} MiB | ${m.verdict} | ${d.verdict} | ${codes(m)} | ${ms.floating_islands} |`);
  if (BOX[j.id]) {
    const req = BOX[j.id]!;
    const got = ms.bbox_um as number[];
    const rep = await gate(file, 'mobile', req.map((v) => v * 5000).join(','));
    bboxRows.push(`| ${j.id} | ${req.join(', ')} | ${got.map((v) => (v / 1e6).toFixed(3)).join(' × ')} | ${(got[0]! / got[1]!).toFixed(2)} : ${(got[1]! / got[2]!).toFixed(2)} (asked ${(req[0]! / req[1]!).toFixed(2)} : ${(req[1]! / req[2]!).toFixed(2)}) | ${rep.measures.box_aspect_deviation_ppm} | ${rep.checks.bbox!.status} |`);
  }
}
w();
w('## `bbox_condition` axis order');
w();
w('Three requests with a different axis dominant each time. The returned GLB\'s bounding box (glTF axes: x, y up, z) follows the request in the same order, so the three integers map to **[x, y, z]** of the delivered file, scaled so the largest side is about 1.9 units.');
w();
w('| Job | `bbox_condition` | Measured x × y × z (units) | Measured ratios | Aspect deviation vs the asked box (ppm) | Conformance check |');
w('|---|---|---|---|---:|---|');
md.push(...bboxRows);
w();
w('The aspect deviation is measured against a declared box proportional to the request, using the 15% (150,000 ppm) tolerance.');
w();
w('## Limits of this run');
w();
w('- Ten jobs, one prompt family for most of them: nothing here is a failure rate. The seed is accepted, but whether it makes output reproducible was not tested (a repeated identical request is deduplicated by the client and would not be sent).');
w('- The queue behaviour (jobs finishing in groups of three, two and two) is from one burst of seven; it is consistent with a limit on simultaneous sub-jobs, not proof of one.');
w('- Download URLs expire; no expiry time is documented or was measured.');
w('- The ledger is the record of spend. It holds the job subscription keys and is kept in `bench/out/`, which git ignores.');
w();
writeFileSync(join(LIVE, 'LIVE_VERIFICATION.md'), md.join('\n') + '\n');
console.error('wrote bench/out/live/LIVE_VERIFICATION.md');
