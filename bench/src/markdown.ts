import type { SmokeCase } from './bundles.ts';
import { fmtInterval, fmtPct } from './stats.ts';

interface SummaryShape {
  fixtures: number;
  fixture_hash_drift: unknown[];
  per_code: Record<string, { n: number; hits: number; recall: number }>;
  controls: { n: number; false_rejects: { id: string; verdict: string; codes: string[] }[]; rate: number };
  false_pass: { error_class_fixtures: number; count: number; ids: string[]; smoke_count: number };
  abstain: { on_fixtures: number; on_smoke: string[]; fail_closed_controls: { name: string; verdict: string }[] };
  label_mismatches: { id: string; problems: string[] }[];
  latency_ms: Record<string, { n: number; p50: number; p95: number; max?: number }>;
  determinism: { asset_runs: number; asset_hash_differences: string[]; smoke_runs: number; smoke_hash_differences: string[]; frame_hashes: { id: string; stable: boolean; sha: string }[] };
}

interface SmokeRow {
  case: SmokeCase;
  verdict: string;
  codes: string[];
  ok: boolean;
  exit: number;
  ms: number;
}

export interface MarkdownInput {
  environment: Record<string, string | number | null>;
  summary: SummaryShape;
  evals: { id: string; ok: boolean; problems: string[] }[];
  smokeRows: SmokeRow[];
  failClosed: { name: string; verdict: string; checks: Record<string, string> }[];
  exits: { name: string; expected: number; actual: number }[];
  positive: SmokeRow[];
  durationS: number;
}

const s = (ms: number) => `${(ms / 1000).toFixed(2)} s`;
const yes = (b: boolean) => (b ? 'yes' : '**NO**');
const list = (xs: string[]) => (xs.length ? xs.join(', ') : 'none');

export function renderMarkdown(i: MarkdownInput): string {
  const e = i.environment;
  const sm = i.summary;
  const lines: string[] = [];
  const w = (t = '') => lines.push(t);

  w('# kensho 72-hour proof: results on synthetic fixtures');
  w();
  w('Generated by `pnpm proof`. Every number below comes from this run; nothing is quoted from elsewhere.');
  w();
  w('## Environment');
  w();
  w(`commit \`${String(e.commit).slice(0, 12)}\` (${e.working_tree_changes} uncommitted change(s)) · ${e.os} · ${e.cpu} · Node ${String(e.node).replace(/^v/, '')} · Chromium ${e.chromium} · three ${e.three} · Playwright ${e.playwright} · glTF validator ${e.gltf_validator}`);
  w();
  w(`WebGL renderer: \`${e.renderer}\``);
  w();
  w(`${sm.fixtures} synthetic asset fixtures (every regenerated file reproduced its committed SHA-256: ${yes(sm.fixture_hash_drift.length === 0)}) and ${i.smokeRows.length} smoke cases, each run twice. Wall time ${i.durationS} s.`);
  w();

  w('## Headline');
  w();
  w(`- Recall on every synthetic G4 code: ${Object.values(sm.per_code).every((v) => v.hits === v.n) ? '**1.0 on all**' : '**below 1.0 somewhere: see table**'}`);
  w(`- False PASS on error-class fixtures: **${sm.false_pass.count}** of ${sm.false_pass.error_class_fixtures} (smoke: ${sm.false_pass.smoke_count})`);
  w(`- False reject on clean controls: **${sm.controls.false_rejects.length}** of ${sm.controls.n}, Wilson 95% ${fmtInterval(sm.controls.false_rejects.length, sm.controls.n)}`);
  w(`- Positive controls fired: **${i.positive.filter((r) => r.ok).length}** of ${i.positive.length}`);
  w(`- Identical verdict hashes across both runs: asset gate ${sm.determinism.asset_runs - sm.determinism.asset_hash_differences.length}/${sm.determinism.asset_runs}, smoke ${sm.determinism.smoke_runs - sm.determinism.smoke_hash_differences.length}/${sm.determinism.smoke_runs}`);
  w(`- ABSTAIN: ${sm.abstain.on_fixtures} on the ${sm.fixtures} asset fixtures; smoke ${sm.abstain.on_smoke.length} (${list(sm.abstain.on_smoke)}), the stalled-load case; ${sm.abstain.fail_closed_controls.filter((f) => f.verdict === 'ABSTAIN').length} of ${sm.abstain.fail_closed_controls.length} asset-gate fail-closed controls`);
  w();

  w('## Asset gate: recall per code (first run)');
  w();
  w('| Code | Fixtures | Detected | Recall | Wilson 95% |');
  w('|---|---:|---:|---:|---|');
  for (const [code, v] of Object.entries(sm.per_code)) w(`| ${code} | ${v.n} | ${v.hits} | ${v.recall.toFixed(3)} | ${fmtInterval(v.hits, v.n)} |`);
  w();
  w(`Recall counts a code as detected when it appears at any severity. A fixture whose report differs from its label in any way (an extra code, a wrong verdict, an abstained check) is listed here: ${sm.label_mismatches.length ? sm.label_mismatches.map((m) => `${m.id} (${m.problems.join('; ')})`).join('; ') : 'none'}.`);
  w();
  w(`False rejects on the ${sm.controls.n} clean controls: ${sm.controls.false_rejects.length ? sm.controls.false_rejects.map((f) => `${f.id} → ${f.verdict} ${f.codes.join(',')}`).join('; ') : 'none, so nothing to fix or explain'}.`);
  w();

  w('## Latency (reported, not enforced)');
  w();
  const L = sm.latency_ms;
  w('| What | n | p50 | p95 | Design target |');
  w('|---|---:|---:|---:|---|');
  w(`| asset-gate, all fixtures (process-internal CLI call, worker thread included) | ${L.asset_gate!.n} | ${s(L.asset_gate!.p50)} | ${s(L.asset_gate!.p95)} | 1–5 s per new asset |`);
  w(`| asset-gate, clean controls only | ${L.asset_gate_clean_controls!.n} | ${s(L.asset_gate_clean_controls!.p50)} | ${s(L.asset_gate_clean_controls!.p95)} | same |`);
  w(`| smoke, runs that launched a browser (cold launch every time) | ${L.smoke_with_browser!.n} | ${s(L.smoke_with_browser!.p50)} | ${s(L.smoke_with_browser!.p95)} | under 6 s warm |`);
  w();

  w('## Smoke: expected against actual');
  w();
  w('| Case | Tier | Hooks | Expected | Actual | Codes seen | Match |');
  w('|---|---|---|---|---|---|---|');
  for (const r of i.smokeRows) w(`| ${r.case.id} | ${r.case.tier} | ${r.case.hooks.join(',') || '-'} | ${r.case.expected.verdict} ${r.case.expected.codes.join(',')} | ${r.verdict} | ${r.codes.join(', ') || '-'} | ${yes(r.ok)} |`);
  w();
  w('Refused bundles never reach a browser. The stalled case holds an asset request open; it must end at the deadline as ABSTAIN.');
  w();

  w('## Positive controls');
  w();
  w('Each probe is made to fire on purpose with a test-only hook, which is named in the report it produces. A probe that cannot fire proves nothing.');
  w();
  w('| Hook | Must fire | Fired | All codes seen |');
  w('|---|---|---|---|');
  for (const r of i.positive) w(`| ${r.case.hooks.join(',')} | ${r.case.expected.codes.join(',')} | ${yes(r.ok)} | ${r.codes.join(', ')} |`);
  w();
  w('Fail-closed controls on the asset gate:');
  w();
  for (const f of i.failClosed) w(`- ${f.name}: **${f.verdict}**; unfinished checks: ${Object.keys(f.checks).length}`);
  w();
  w('Exit codes from real processes: ' + i.exits.map((x) => `${x.name} → ${x.actual}${x.actual === x.expected ? '' : ` (expected ${x.expected})`}`).join('; ') + '.');
  w();

  w('## Determinism');
  w();
  w(`Verdict hashes (everything except timings) differing between the two runs: asset gate ${list(sm.determinism.asset_hash_differences)}; smoke ${list(sm.determinism.smoke_hash_differences)}.`);
  const unstable = sm.determinism.frame_hashes.filter((f) => !f.stable);
  w();
  w(`Last-frame pixel hashes: ${sm.determinism.frame_hashes.length - unstable.length} of ${sm.determinism.frame_hashes.length} identical across the two runs${unstable.length ? `; unstable: ${unstable.map((f) => f.id).join(', ')}` : ''}. Reported either way; the frame hash is kept out of the verdict hash.`);
  w();

  w('## What this does not show');
  w();
  w('- **Real GPUs.** SwiftShader is a CPU rasteriser. Fill rate, thermals and driver bugs are untested.');
  w('- **Real assets.** All input is synthetic, with defects the fixture writer put there. Recall of 1.0 here is expected by construction and says nothing about defects real generators produce. The false-reject rate is for 40 synthetic controls, not for generated assets. Not run: the five frozen props from the earlier orchestrator and the 20-credit generation batch.');
  w('- **That the harness matches a production runtime.** The smoke test loads a minimal three.js scene, not a production build. The "player is visible from the spawn camera" check does not exist yet, and the frame check only detects a uniform frame.');
  w('- **Cross-browser behaviour.** One Chromium build only: no Firefox or WebKit parity, no bit-exact replay claim.');
  w('- **Thresholds are this proof\'s choices where the design gave none.** Primitive and material budgets, the 1% island area share, the degenerate-triangle area, the 60,000-triangle hull source cap and the primitive-fit ratios are configuration, not findings.');
  w('- **Colliders are approximate.** Box fits are axis-aligned, there is no capsule fit and no convex decomposition, and a hull is capped by direction sampling. Texture memory is estimated from image headers (width × height × 4 × 4/3), not measured on a device.');
  w('- **Latency is not comparable with the design targets.** Each smoke run launches a fresh browser on a laptop CPU, and asset runs include worker start-up.');
  w('- **Out of scope for this build:** G0–G3, G5 and G7; the WebGPU pass; CoACD and the Python services; the MCP server, the repair loop and the runtime guards; any private integration profile. Providers other than the synthetic oracle are stubs that throw NOT_CONFIGURED.');
  w();
  return lines.join('\n') + '\n';
}

export { fmtPct };
